function render(list=poems){
  visiblePoems=list;
  grid.innerHTML=list.map((p)=>`<article class="poem-card" data-number="${p[0]}"><div class="poem-index">POEM ${p[0]}</div><div class="poem-title">${p[1]}</div><div class="poem-arrow"><i class="fa-solid fa-arrow-right"></i></div></article>`).join('');
  noResults.hidden=list.length!==0;
  grid.querySelectorAll('.poem-card').forEach(card=>card.addEventListener('click',()=>openPoem(card.dataset.number)));
}
function openPoem(number){
  const idx=poems.findIndex(p=>p[0]===number);
  if(idx<0)return;
  currentIndex=idx;
  const p=poems[idx];
  readerNumber.textContent=`POEM ${p[0]}`;
  readerTitle.textContent=p[1];
  readerText.textContent=p[2];
  updateNav();
  reader.classList.add('open');
  reader.setAttribute('aria-hidden','false');
  document.body.style.overflow='hidden';
}
function updateNav(){prev.disabled=currentIndex===0;next.disabled=currentIndex===poems.length-1}
function closeReader(){reader.classList.remove('open');reader.setAttribute('aria-hidden','true');document.body.style.overflow=''}
