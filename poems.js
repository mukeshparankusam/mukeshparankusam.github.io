document.querySelectorAll('[data-close-reader]').forEach(el=>el.addEventListener('click',closeReader));
document.addEventListener('keydown',e=>{if(e.key==='Escape')closeReader();if(reader.classList.contains('open')&&e.key==='ArrowLeft'&&currentIndex>0)openPoem(poems[currentIndex-1][0]);if(reader.classList.contains('open')&&e.key==='ArrowRight'&&currentIndex<poems.length-1)openPoem(poems[currentIndex+1][0])});
search.addEventListener('input',()=>{const q=search.value.trim().toLowerCase();render(q?poems.filter(p=>(p[0]+' '+p[1]+' '+p[2]).toLowerCase().includes(q)):poems)});
